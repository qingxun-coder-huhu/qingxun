# frozen_string_literal: true

module Prompts
  # 分支建议提示词
  #
  # 业务逻辑：
  #   用户在页面上点击「AI建议分支」时，模型根据主线描述和已有分支，额外给出 3 条
  #   值得覆盖的分支测试场景。用户自行勾选是否采纳；不采纳不影响已有分支。
  #   点「自定义」时走 build_custom：由用户指定一个/多个场景，模型据此生成 1~N 条。
  #
  # 隐性知识：
  #   1. 「全量描述」= 该分支**实际执行流程**写完整：按执行顺序写「命令 / 报文 / 处理逻辑」，
  #      只写这个分支真正会执行的步骤，从第一条实际命令写到最后一条。与主线描述同一种格式。
  #   2. **不是**把主线的所有命令都列一遍再标"（不执行）"——实测模型会这样退化成
  #      "命令 show boot / 报文（不执行）/ 处理逻辑：不执行"的占位清单，徒增噪音。
  #      流程在哪一步结束就写到哪一步为止。
  #   3. 不要"场景前提 / 验证点 / 用于验证…"这类元信息说明，直接进入命令-报文-处理逻辑；
  #      分支之间的差异自然体现在实际执行的命令和报文里。
  #   4. 建议之间、建议与已有分支之间都不能重复或高度重叠。
  #   5. **自定义场景不凑数**：条数由用户描述决定（一个场景一条；多个独立场景多条），
  #      不像 build 那样固定要 3 条——硬凑会塞进用户没要求的场景。
  module BranchSuggestion
    MAX_SUGGESTIONS = 3
    # 自定义场景的上限：用户可能一口气列多个场景，这里只做上限保护，不强制凑满
    MAX_CUSTOM_SUGGESTIONS = 5

    def self.build(mainline_description, existing_branches = [], avoid_branches = [])
      <<~PROMPT
        主线任务描述（分支描述要和它写成同一种风格）：
        ```
        #{Prompts.escape_interpolation(mainline_description)}
        ```#{existing_branches_section(existing_branches)}#{avoid_branches_section(avoid_branches)}

        请再给出 #{MAX_SUGGESTIONS} 条值得覆盖的**分支测试场景**。每条建议就是该分支
        **实际执行流程**的一份完整描述：按执行顺序写「命令 → 报文 → 处理逻辑」，
        只写这个分支真正会执行的步骤。

        硬性要求：
        1. 只写该分支下**实际会执行**的命令，按执行顺序排列；每条命令后紧跟它的示例报文，
           以及脚本对该报文的处理与判定。
        2. **不要列出不会执行的命令**：禁止出现"（不执行）""不执行""同主线"这类占位步骤，
           也不要用"其余同主线""同上"省略。流程在某一步就结束时，写到那一步为止即可，
           后面的命令根本不用提。
        3. 不要写"场景前提""验证点""用于验证…"这类说明性、元信息式的话，直接进入
           命令-报文-处理逻辑。分支与主线的差异自然体现在实际执行的命令和报文中。
        4. 与主线同一种格式：命令 / 报文 / 处理逻辑。
        5. 恰好 #{MAX_SUGGESTIONS} 条，彼此不重复，也不与已有分支重复或高度重叠。
        6. 优先覆盖有实际意义的分支路径，例如：命令执行失败 / 设备返回错误回显、
           关键报文为空或格式异常、不同型号或软件版本差异、功能未配置 / 权限不足 /
           enable 失败、输出被截断 / 字段缺失 / 数值越界。
        7. 命令和报文必须具体、可直接用于构造该分支的模拟测试环境；异常分支给真实的错误回显。
        8. 每条都是自洽的完整流程描述，可独立阅读，不依赖主线或其他分支的上下文。
        9. 只描述测试场景，不要给出脚本代码或实现步骤。
        10. **不得超出主线的要求（最重要）**：分支只能换一组报文/数值去触发主线**已声明**的
            规则；**禁止**新增主线未声明的判定、阈值、失败处理或终止条件；**禁止**把主线
            某一步声明的规则挪到别的命令上（规则跟着它所在的命令走）；**禁止**与主线的
            结论相矛盾。判断某条规则能不能用，以"主线描述里是否写了"为准，主线没写就不要用。

        示例一（流程提前结束：只写到实际执行的最后一步，后续命令不再列）：
        ```
        命令 display version
        报文
        ZXCTN 6500-2
        处理逻辑：按正则匹配 ZXCTN 9000- 失败，判定型号不符，输出"模板与设备类型不符"并结束
        整个检查流程（后续命令不再执行，无需列出）。
        ```

        示例二（某一步失败但流程继续：把继续执行的步骤按顺序写全）：
        ```
        命令 display fan
        报文
        Fan 1: Normal
        Fan 2: Fault
        处理逻辑：风扇 2 状态非 Normal，记录该风扇异常为失败项并给出可读原因，继续后续检查。
        命令 display power
        报文
        Power 1: Normal
        处理逻辑：电源状态正常，记录为通过。
        ```

        只输出 JSON，包含在 ```json 代码块中，格式如下：
        ```json
        {
          "branches": [
            { "name": "简短名称", "description": "该分支实际执行流程的完整描述（命令/报文/处理逻辑）" }
          ]
        }
        ```
      PROMPT
    end

    # 自定义场景：由用户指定要覆盖的分支场景，模型据此生成 1~N 条（条数随输入而定）
    def self.build_custom(mainline_description, custom_requirement, existing_branches = [], avoid_branches = [])
      <<~PROMPT
        主线任务描述（分支描述要和它写成同一种风格）：
        ```
        #{Prompts.escape_interpolation(mainline_description)}
        ```#{existing_branches_section(existing_branches)}#{avoid_branches_section(avoid_branches)}

        用户指定的分支场景（请据此生成，不要生成用户没要求的场景）：
        ```
        #{Prompts.escape_interpolation(custom_requirement)}
        ```

        请把上面的场景写成**分支实际执行流程**的一份完整描述：按执行顺序写
        「命令 → 报文 → 处理逻辑」，只写这个分支真正会执行的步骤。

        硬性要求：
        1. **条数由用户描述决定**：用户只描述了一个场景就只生成 1 条；描述了多个彼此独立的场景时，
           为每个场景各生成 1 条，最多 #{MAX_CUSTOM_SUGGESTIONS} 条。
           **禁止为了凑数而生成用户没要求的场景。**
        2. 只写该分支下**实际会执行**的命令，按执行顺序排列；每条命令后紧跟它的示例报文，
           以及脚本对该报文的处理与判定。
        3. **不要列出不会执行的命令**：禁止出现"（不执行）""不执行""同主线"这类占位步骤，
           也不要用"其余同主线""同上"省略。流程在某一步就结束时，写到那一步为止即可。
        4. 不要写"场景前提""验证点""用于验证…"这类说明性、元信息式的话，直接进入
           命令-报文-处理逻辑。
        5. 与主线同一种格式：命令 / 报文 / 处理逻辑。
        6. 命令和报文必须具体、可直接用于构造该分支的模拟测试环境；异常分支给真实的错误回显。
        7. 每条都彼此不重复，也不与已有分支、上一批建议重复或高度重叠。
        8. 只描述测试场景，不要给出脚本代码或实现步骤。
        9. **不得超出主线的要求（最重要）**：分支只能换一组报文/数值去触发主线**已声明**的
           规则；**禁止**新增主线未声明的判定、阈值、失败处理或终止条件；**禁止**把主线
           某一步声明的规则挪到别的命令上（规则跟着它所在的命令走）；**禁止**与主线的
           结论相矛盾。判断某条规则能不能用，以"主线描述里是否写了"为准，主线没写就不要用。
           若用户指定的场景需要主线未声明的规则，**不要自行添加**，只按主线允许的范围写。

        只输出 JSON，包含在 ```json 代码块中，格式如下：
        ```json
        {
          "branches": [
            { "name": "简短名称", "description": "该分支实际执行流程的完整描述（命令/报文/处理逻辑）" }
          ]
        }
        ```
      PROMPT
    end

    def self.system_prompt
      <<~PROMPT
        角色：
          你是一个网络设备 CLI 自动化测试专家，擅长从需求中提炼容易被忽略的异常与边界
          分支。你的任务是为主流程脚本补充值得覆盖的分支测试场景。

        硬性规则：
          1. 恰好给出 #{MAX_SUGGESTIONS} 条建议。
          2. 每条建议是该分支**实际执行流程**的完整描述：按执行顺序写
             「命令 / 报文 / 处理逻辑」，只写这个分支真正会执行的步骤，从第一条实际命令写到最后一条。
          3. **禁止列出不会执行的命令**：不得出现"（不执行）""不执行"这类占位步骤，也不得用
             "其余同主线""同上"省略；流程提前结束就写到结束那一步为止。
          4. 不要写"场景前提""验证点""用于验证…"这类元信息说明，直接进入命令-报文-处理逻辑。
          5. 命令和报文要具体，可独立用于构造该分支的模拟测试环境。
          6. 不与已有分支重复，不彼此重叠。
          7. **不得超出主线**：分支只能触发主线已声明的规则；不得新增主线未声明的判定/阈值/
             失败处理/终止条件；不得把某一步的规则挪到别的命令上；不得与主线结论矛盾。
          8. 只输出这段流程描述，不输出代码或实现方案。
          9. 只输出 JSON，不输出多余解释。
      PROMPT
    end

    # 自定义场景的系统提示：在通用规则基础上，把"恰好 3 条"换成"按用户描述定条数"
    def self.custom_system_prompt
      system_prompt + <<~PROMPT

        本次的额外约束：
          用户会指定一个或多个分支场景，你据此生成分支。用户只指定一个场景时就只给 1 条；
          描述里包含多个彼此独立的场景时才给多条，最多 #{MAX_CUSTOM_SUGGESTIONS} 条。
          **不要补充用户没要求的场景，也不要为了凑成固定条数而生成多余分支。**
      PROMPT
    end

    # 已有分支段（build / build_custom 共用，输出保持一致）
    def self.existing_branches_section(existing_branches)
      if Array(existing_branches).any?
        lines = Array(existing_branches).each_with_index.map do |b, i|
          name = b[:name] || b['name']
          desc = b[:description] || b['description']
          "#{i + 1}. #{name}：#{desc}"
        end.join("\n")
        "\n\n已有分支（不要与它们重复或高度重叠）：\n#{Prompts.escape_interpolation(lines)}"
      else
        "\n\n目前还没有任何分支场景。"
      end
    end

    # 上一批建议段（"换一批"时避免重复）
    def self.avoid_branches_section(avoid_branches)
      if Array(avoid_branches).any?
        lines = Array(avoid_branches).each_with_index.map do |b, i|
          name = b[:name] || b['name']
          desc = b[:description] || b['description']
          "#{i + 1}. #{name}：#{desc}"
        end.join("\n")
        "\n\n上一批已经给过以下建议（这次请换一批不同的，不要再重复或只换措辞）：\n" \
          "#{Prompts.escape_interpolation(lines)}"
      else
        ""
      end
    end
  end
end
